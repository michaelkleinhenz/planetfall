// Builds the Magnetic Scrolls games from their original 68000 assembly source.
//
// Magnetic Scrolls' own tools (the as68 assembler and the lnk linker, in C,
// from the same source release) are compiled first; then each game is
// assembled and linked exactly as its makefile (or link list) says, which gives
// the "prog" file the games ran from: the 68000 program with its noun table,
// dictionary and symbol table. The program, the game's messages and its symbols
// are written to web/src/games/<id>/ for the browser.
//
// Needs a C compiler, make and flex.
//
// Usage: node tools/magnetic/build.mjs [game|all]

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { parseProg, Machine } from '../../web/src/engine/ms/machine.js';
import { GAMES } from './games.mjs';
import { parseMag } from './mag.mjs';
import { magMemory } from './probe.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const SRC = path.join(ROOT, 'games/magnetic/src');

const run = (cmd, args, cwd) => execFileSync(cmd, args, { cwd, stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 64 << 20 }).toString();

function buildTools(work) {
  const bin = path.join(work, 'tools/bin');
  fs.mkdirSync(bin, { recursive: true });
  for (const tool of ['as68', 'lnk']) {
    const dir = path.join(work, 'tools', tool);
    fs.mkdirSync(path.join(dir, 'obj'), { recursive: true });
    // The tools are 1980s C: build them leniently.
    run('make', ['-s', 'CC=gcc -fcommon -w -std=gnu89', tool], dir);
    fs.copyFileSync(path.join(dir, tool), path.join(bin, tool));
  }
  return bin;
}

/** Assemble and link one game; returns the prog file's bytes. */
function assemble(work, cfg) {
  const obj = path.join(work, cfg.dir, 'obj');
  if (cfg.makefile) {
    // equates.i is checked in already; its makefile rule needs files that are
    // not part of the release, so tell make it is up to date.
    run('make', ['-s', '-o', 'equates.i', 'prog'], obj);
  } else {
    // No makefile: assemble every module named in the link list (lfile) from
    // the game's own sources or the shared "newcommonlast" library.
    const modules = fs.readFileSync(path.join(obj, 'lfile'), 'latin1').split(/\r?\n/)
      .map((l) => l.trim()).filter((l) => l && !l.startsWith('#') && l.endsWith('.o'));
    for (const o of modules) {
      const base = o.slice(0, -2);
      const src = cfg.search.map((d) => path.join(work, d, base))
        .flatMap((p) => [`${p}.asm`, `${p}.elt`]).find((p) => fs.existsSync(p));
      if (!src) throw new Error(`${cfg.id}: no source for ${o}`);
      run(path.join(work, 'tools/bin/as68'), [src, '-i', cfg.search.map((d) => path.join(work, d)).join(','), '-o', o, 'opt', 'qs'], obj);
    }
    run(path.join(work, 'tools/bin/lnk'), ['-tpv', '-l', 'lfile', '-o', 'prog'], obj);
  }
  return new Uint8Array(fs.readFileSync(path.join(obj, 'prog')));
}

// The remastered text files carry Strand Games' markup for their own front
// end: links "[text](command)" and "[text]", emphasis "\ text \" and coloured
// letters "#J{color:red}". The text itself is kept; the markup is removed.
export function cleanMessage(s) {
  return s
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\[([^\]]*)\]/g, '$1')
    .replace(/#(.)\{[^}]*\}/g, '$1')
    .replace(/\\_|_\\/g, '')
    .replace(/\\ ?| ?\\/g, (m) => (m.includes(' ') ? ' ' : ''))
    .replace(/ {2,}/g, ' ');
}

function writeGame(cfg, prog) {
  const { code, wtable, symbols } = parseProg(prog);
  const text = fs.readFileSync(path.join(SRC, cfg.text), 'latin1').split(/\r?\n/);
  const messages = text.map(cleanMessage);
  const out = path.join(ROOT, 'web/src/games', cfg.id);
  fs.mkdirSync(out, { recursive: true });
  const b64 = (u8) => (u8 ? Buffer.from(u8).toString('base64') : null);
  const header = `// ${cfg.title}: AUTO-GENERATED by tools/magnetic/build.mjs from the original
// 68000 assembly source of ${cfg.title} (c) ${cfg.year} Magnetic Scrolls Ltd., as released by
// Strand Games under the Voidware Public Source Licence 1.0 (non-commercial use;
// https://strandgames.com/legal/strandPSL1.txt). Do not edit by hand.\n\n`;
  const sorted = Object.fromEntries(Object.entries(symbols).sort((a, b) => a[1] - b[1]));
  fs.writeFileSync(path.join(out, 'game.js'), header +
    `// How the game ran: the program is Magnetic Scrolls' 68000 code, run by\n// engine/ms (a 68000 core and the Magnetic Scrolls host calls).\n` +
    `export const ENGINE = 'magnetic';\n` +
    `export const NET_SIZE = ${cfg.netSize};\n` +
    `export const SCORE_SCALE = ${cfg.scoreScale ?? 1};\n` +
    `// PICTURE_INDEX: one picture number per room ('rooms', The Pawn), or a list of\n// (picture, room, version) entries ('list').\n` +
    `export const PICTURE_INDEX = '${cfg.pictureIndex ?? 'list'}';\n\n` +
    `// The assembler's symbol table: every label of the original source and its address.\n` +
    `export const SYMBOLS = ${JSON.stringify(sorted)};\n`);
  fs.writeFileSync(path.join(out, 'story-data.js'), header +
    `// The assembled program (code and data), the word table (dictionary) where the\n// game keeps it apart, and the game's messages, one per line of its text file.\n` +
    `export const CODE_BASE64 = ${JSON.stringify(b64(code))};\n` +
    `export const WTABLE_BASE64 = ${JSON.stringify(b64(wtable))};\n` +
    `export const MESSAGES = ${JSON.stringify(messages, null, 0).replace(/","/g, '",\n"')};\n`);
  return { code: code.length, wtable: wtable?.length ?? 0, messages: messages.length, symbols: Object.keys(symbols).length };
}

/** A game without released source: its original release, as it is. */
function writeMagGame(cfg) {
  const g = parseMag(new Uint8Array(fs.readFileSync(path.join(ROOT, 'games/magnetic/original', cfg.mag))));
  const mem = magMemory(g);
  // Rooms: the largest location of a room noun (byte 6 bit 6) in the noun table,
  // which the game hands over at start (SETNOUNS); read it from a first run.
  const out = path.join(ROOT, 'web/src/games', cfg.id);
  fs.mkdirSync(out, { recursive: true });
  const b64 = (u8) => (u8 ? Buffer.from(u8).toString('base64') : null);
  const header = `// ${cfg.title}: AUTO-GENERATED by tools/magnetic/build.mjs from the original release
// of ${cfg.title} (c) ${cfg.year} Magnetic Scrolls Ltd. (${cfg.mag}). Do not edit by hand.\n\n`;
  const rooms = countRooms(g, mem);
  const symbols = { ROOM: cfg.room, NETWORK: cfg.network, NET_END: cfg.network + cfg.netSize * rooms };
  fs.writeFileSync(path.join(out, 'game.js'), header +
    `// The program is Magnetic Scrolls' original 68000 code (no source was released),\n// run by engine/ms (a 68000 core and the Magnetic Scrolls host calls).\n` +
    `export const ENGINE = 'magnetic';\n` +
    `export const NET_SIZE = ${cfg.netSize};\n` +
    `export const SCORE_SCALE = 1;\n` +
    `// Memory as the original interpreters set it up.\n` +
    `export const MEMORY = ${JSON.stringify(mem)};\n` +
    `// Score and moves (or the time) come from the game's own status line.\n` +
    `export const STATUS_LINE = ${cfg.clock ? "'clock'" : "'score'"};\n` +
    `export const PICTURE_INDEX = null;\n\n` +
    `// The addresses the app reads (found with tools/magnetic/probe.mjs; see games.mjs).\n` +
    `export const SYMBOLS = ${JSON.stringify(symbols)};\n`);
  fs.writeFileSync(path.join(out, 'story-data.js'), header +
    `// The program, the dictionary and the game's messages (decoded from the release's\n// compressed text).\n` +
    `export const CODE_BASE64 = ${JSON.stringify(b64(g.code))};\n` +
    `export const WTABLE_BASE64 = ${JSON.stringify(b64(g.dict))};\n` +
    `export const MESSAGES = ${JSON.stringify(g.messages, null, 0).replace(/","/g, '",\n"')};\n`);
  return { code: g.code.length, wtable: g.dict?.length ?? 0, messages: g.messages.length, symbols: rooms };
}

function countRooms(g, mem) {
  const m = new Machine({ code: g.code, wtable: g.dict, messages: g.messages, ...mem });
  m.seed(1);
  m.run();
  const sections = [[]];
  for (const c of g.dict ?? []) { if (c === 0x81) break; if (c === 0x82) sections.push([]); else if (c & 0x80) sections[sections.length - 1].push(c); }
  const nouns = sections[6]?.length ?? 0;
  let rooms = 0;
  for (let n = 1; n <= nouns; n++) {
    const a = m.nouns.data + 14 * n;
    const loc = (m.mem[a + 8] << 8) | m.mem[a + 9];
    // (the exits table holds room numbers in bytes; a few room nouns hold other values)
    if ((m.mem[a + 6] & 0x40) && loc < 256) rooms = Math.max(rooms, loc);
  }
  return rooms;
}

function main() {
  const which = process.argv[2] || 'all';
  const ids = which === 'all' ? Object.keys(GAMES) : [which];
  const work = fs.mkdtempSync(path.join(os.tmpdir(), 'magnetic-'));
  try {
    for (const id of ids) if (!GAMES[id]) throw new Error(`Unknown game ${id}`);
    // The assembler and linker are only needed for games built from source.
    if (ids.some((id) => !GAMES[id].mag)) {
      fs.cpSync(SRC, work, { recursive: true });
      buildTools(work);
    }
    for (const id of ids) {
      const cfg = GAMES[id];
      if (cfg.mag) {
        const info = writeMagGame(cfg);
        console.log(`${id}: ${info.code} bytes of code, ${info.wtable} bytes of dictionary, ${info.messages} messages, ${info.symbols} rooms (original release)`);
        continue;
      }
      const prog = assemble(work, cfg);
      const info = writeGame(cfg, prog);
      console.log(`${id}: ${info.code} bytes of code, ${info.wtable} bytes of word table, ${info.messages} messages, ${info.symbols} symbols`);
    }
  } finally {
    fs.rmSync(work, { recursive: true, force: true });
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
