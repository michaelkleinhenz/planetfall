// Builds the Legend Entertainment games for the app:
//   web/img/legend/<id>.pak         the files the game needs, in one pack
//   web/src/games/<id>/game.js      the engine settings
//   web/src/games/<id>/story-data.js where the pack is
//
// The games run as their original DOS programs (engine/legend); nothing is
// translated. Music and sound effects are left out (the app has no sound for
// these games), and so are the 256-colour pictures, which only the 320x200
// mode uses.
//
//   node tools/legend/build.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

const GAMES = [
  {
    id: 'gateway',
    dir: 'games/legend/gateway',
    title: "Frederik Pohl's Gateway",
    exe: 'GATE.EXE',
    prefix: 'GATE',
    // The game's files, as patterns; everything else in the directory is left out.
    keep: /^(GATE\.EXE|GATEMAIN\.(EXE|OVL)|GATE\.RTL|RTLINKST\.COM|GATESTR\.DAT|VOCAB\.DAT|OBJECT\.DAT|RESTART\.DAT|HINTBOOK\.TXT|GATE_[0-2]\d\d\.(PIC|RGN|FNT)|GATE_4\d\d\.(PIC|FNT))$/,
  },
];

function pack(entries) {
  const head = [];
  head.push(...Buffer.from('LGPK'), entries.length & 0xff, entries.length >> 8);
  for (const [name, data] of entries) {
    head.push(name.length, ...Buffer.from(name));
    const n = data.length;
    head.push(n & 0xff, (n >> 8) & 0xff, (n >> 16) & 0xff, (n >>> 24) & 0xff);
  }
  return Buffer.concat([Buffer.from(head), ...entries.map(([, d]) => d)]);
}

for (const g of GAMES) {
  const dir = path.join(root, g.dir);
  const names = fs.readdirSync(dir).map((n) => n.toUpperCase()).filter((n) => g.keep.test(n)).sort();
  const entries = names.map((n) => {
    const actual = fs.readdirSync(dir).find((x) => x.toUpperCase() === n);
    return [n, fs.readFileSync(path.join(dir, actual))];
  });
  const out = path.join(root, 'web/img/legend', `${g.id}.pak`);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  const bytes = pack(entries);
  fs.writeFileSync(out, bytes);
  const gameDir = path.join(root, 'web/src/games', g.id);
  fs.mkdirSync(gameDir, { recursive: true });
  fs.writeFileSync(path.join(gameDir, 'game.js'), `// ${g.title}: AUTO-GENERATED by tools/legend/build.mjs. Do not edit by hand.

// The game is Legend Entertainment's original DOS program (no source was
// released), run by engine/legend (an x86 core and just enough of DOS).
export const ENGINE = 'legend';
export const CONFIG = ${JSON.stringify({ exe: g.exe, args: '', prefix: g.prefix })};
`);
  fs.writeFileSync(path.join(gameDir, 'story-data.js'), `// ${g.title}: AUTO-GENERATED by tools/legend/build.mjs. Do not edit by hand.
// The game's original files, packed (relative to web/).
export const PACK = 'img/legend/${g.id}.pak';
export const FILES = ${JSON.stringify(names)};
`);
  console.log(`${g.id}: ${names.length} files, ${(bytes.length / 1024).toFixed(0)} KB -> ${path.relative(root, out)}`);
}
